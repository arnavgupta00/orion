import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(projectRoot, '../../career-evidence/career-evidence.md');
const outputPath = resolve(projectRoot, 'src/knowledge/arnavCareerEvidence.generated.ts');
const checkOnly = process.argv.includes('--check');

const source = await readFile(sourcePath, 'utf8');
const sanitized = sanitize(source);
const updated = /^- Updated: `([^`]+)`/m.exec(sanitized)?.[1] ?? 'unknown';
const output = `// Generated by pnpm sync:career. Do not edit by hand.\n`
  + `export const ARNAV_EVIDENCE_UPDATED = ${JSON.stringify(updated)};\n`
  + `export const ARNAV_CAREER_EVIDENCE = ${JSON.stringify(sanitized)};\n`;

if (checkOnly) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== output) {
    console.error('Career evidence snapshot is out of date. Run pnpm sync:career.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Updated ${outputPath}`);
}

function sanitize(markdown) {
  return markdown
    .replace(/`\/Users\/[^/]+\/programming\/([^`]+)`/g, (_match, relative) => `\`project:${relative}\``)
    .replace(/`\/Users\/[^/]+\/\.codex\/[^`]+`/g, '`private evidence source omitted`')
    .replace(/`(?:linkedin|upwork)-[a-z-]+\.png`/gi, '`profile source capture`')
    .replace(/(?:linkedin|upwork)-[a-z-]+\.png/gi, 'profile source capture')
    .replace(/\/Users\/[^/]+\/[\w./*-]+/g, '[local path omitted]')
    .replace(/[ \t]+$/gm, '')
    .trim();
}
